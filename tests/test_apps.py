def windowed(path):
    return True                 # pretend every .exe opens a window; the console check is tested below


def allowed(entry):
    return is_allowed(entry, windowed)


@pytest.mark.parametrize("entry", SAFE, ids=lambda e: e.name)
def test_ordinary_apps_are_allowed(entry):
    assert allowed(entry)


@pytest.mark.parametrize("entry", DANGEROUS, ids=lambda e: e.name)
def test_dangerous_entries_are_blocked(entry):
    assert not allowed(entry)


def test_a_renamed_shortcut_is_judged_by_its_real_program():
    disguised = AppEntry("Spotify Helper", "Microsoft.AutoGenerated.{0}", r"C:\Windows\System32\WindowsPowerShell\v1.0\powershell.exe")
    assert not allowed(disguised)


def test_console_programs_are_blocked_even_if_not_on_the_list():
    tool = AppEntry("Some Tool", PF + r"\tool\tool.exe")
    assert is_allowed(tool, lambda path: True) and not is_allowed(tool, lambda path: False)


@pytest.mark.skipif(sys.platform != "win32", reason="needs Windows programs")
def test_console_check_reads_the_real_program_header():
    system32 = Path(r"C:\Windows\System32")
    assert is_windowed_exe(str(system32 / "notepad.exe"))
    assert not is_windowed_exe(str(system32 / "cmd.exe"))
    assert not is_windowed_exe(str(system32 / "WindowsPowerShell" / "v1.0" / "powershell.exe"))
    assert not is_windowed_exe(str(system32 / "drivers" / "etc" / "hosts"))   # not a program at all
    assert not is_windowed_exe(r"C:\no\such\file.exe")


