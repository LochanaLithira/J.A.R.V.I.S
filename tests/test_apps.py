def test_launch_failure_gives_a_safe_message(tmp_path):
    def boom(launch_id):
        raise OSError(r"C:\secret\path")

    r = gate(tmp_path, boom).execute("open_app", {"name": "word"})
    assert not r.ok and "secret" not in r.message


def test_an_unreadable_app_list_is_a_safe_refusal(tmp_path):
    def broken():
        raise OSError("COM exploded")

    g = Gate(make_app_tools(AppCatalog(lister=broken), lambda i: None), AuditLog(tmp_path / "log.jsonl"))
    r = g.execute("open_app", {"name": "word"})
    assert not r.ok and r.message == "I couldn't read the list of apps."


