# ---- finding an app by the name you said --------------------------------------------------------

def catalog(entries=SAFE + DANGEROUS):
    return AppCatalog(lister=lambda: entries, allowed=allowed)


@pytest.mark.parametrize("spoken, name", [
    ("spotify", "Spotify"), ("Spotify", "Spotify"), ("the calculator", "Calculator"), ("word", "Word"),
    ("edge", "Microsoft Edge"), ("visual studio code", "Visual Studio Code"), ("notepad app", "Notepad"),
    ("file explorer", "File Explorer"), ("outlook", "Outlook"),
])
def test_names_are_matched_like_people_say_them(spoken, name):
    assert catalog().find(spoken).name == name


def test_two_matches_are_asked_about():
    notes = [AppEntry("Sticky Notes", "Microsoft.MicrosoftStickyNotes_8wekyb3d8bbwe!App"),
             AppEntry("Sticky Notes (new)", "Microsoft.Office.OneNote.MemoryPreview",
                      r"C:\Program Files\Microsoft Office\root\Office16\ONENOTE.EXE")]
    with pytest.raises(ToolError, match=r"Did you mean Sticky Notes or Sticky Notes \(new\)\?"):
        catalog(notes).find("sticky")
    assert catalog(notes).find("sticky notes").name == "Sticky Notes"     # an exact name wins


@pytest.mark.parametrize("spoken", ["powershell", "command prompt", "terminal", "task manager", "registry editor",
                                    "git bash", "python", "run", "control panel", "quick assist", "ubuntu"])
def test_blocked_apps_cannot_be_found(spoken):
    with pytest.raises(ToolError, match="allowed to open"):
        catalog().find(spoken)


def test_the_list_is_cached_then_refreshed():
    calls, now = [], {"t": 0.0}

    def lister():
        calls.append(1)
        return SAFE

    c = AppCatalog(lister=lister, allowed=allowed, clock=lambda: now["t"], refresh_seconds=600)
    c.find("word"); c.find("spotify")
    assert len(calls) == 1
    now["t"] = 601
    c.find("word")
    assert len(calls) == 2


def test_names_for_a_running_program():
    assert catalog().names_for_program(r"c:\program files\microsoft office\root\office16\winword.exe") == ["Word"]


# ---- through the gate ---------------------------------------------------------------------------

def gate(tmp_path, launcher, entries=SAFE + DANGEROUS):
    return Gate(make_app_tools(catalog(entries), launcher), AuditLog(tmp_path / "log.jsonl"), max_calls=1000)


def test_open_app_uses_only_the_windows_id(tmp_path):
    opened = []
    r = gate(tmp_path, opened.append).execute("open_app", {"name": "spotify"})
    assert r.ok and r.message == "Opening Spotify." and opened == ["SpotifyAB.SpotifyMusic_zpdnekdrzrea0!Spotify"]


